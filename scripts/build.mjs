import { createHash } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { outputDirectory, projectRoot, sourceEntries } from './project.mjs';
import { generateSeoFiles } from './seo.mjs';
import { addSupportFooter } from './support.mjs';

export async function buildSite({ quiet = false } = {}) {
  const entries = await sourceEntries();
  const workerTemplate = await readFile(path.join(projectRoot, 'src/service-worker.js'), 'utf8');
  const hash = createHash('sha256');
  const files = new Map();
  for (const { source, output } of entries) files.set(output, await readFile(source));
  const seo = await generateSeoFiles(files);
  await addSupportFooter(files);

  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });

  for (const [output, bytes] of [...files].sort(([left], [right]) =>
    left.localeCompare(right, 'en'),
  )) {
    const destination = path.join(outputDirectory, output);
    hash.update(output).update('\0').update(bytes).update('\0');
    await mkdir(path.dirname(destination), { recursive: true });
    await writeFile(destination, bytes);
  }

  hash.update(workerTemplate);
  const cacheName = `petits-moments-${hash.digest('hex').slice(0, 16)}`;
  // Keep installation light; activity and selection pages are cached when visited.
  const appShell = ['./', ...files.keys()]
    .filter(
      (output) =>
        !/^(?:activites|selections|en\/activities|en\/collections)\//.test(output) &&
        !['sitemap.xml', 'robots.txt'].includes(output),
    )
    .map((output) => (output === './' ? output : `./${output}`));
  const worker = [
    '// Generated by npm run build. Edit src/service-worker.js instead.',
    `const CACHE = ${JSON.stringify(cacheName)};`,
    `const APP_SHELL = ${JSON.stringify(appShell, null, 2)};`,
    workerTemplate,
  ].join('\n');

  await writeFile(path.join(outputDirectory, 'sw.js'), worker);
  if (!quiet)
    console.log(
      `Built ${files.size + 1} files, ${seo.activities} bilingual activities and ${seo.pages} indexable pages in dist/ (${cacheName}). Canonical origin: ${seo.siteUrl}`,
    );
  return { files: files.size + 1, cacheName, ...seo };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildSite();
}
