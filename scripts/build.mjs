import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { outputDirectory, projectRoot, sourceEntries } from './project.mjs';

export async function buildSite({ quiet = false } = {}) {
  const entries = await sourceEntries();
  const workerTemplate = await readFile(path.join(projectRoot, 'src/service-worker.js'), 'utf8');
  const hash = createHash('sha256');

  await rm(outputDirectory, { recursive: true, force: true });
  await mkdir(outputDirectory, { recursive: true });

  for (const { source, output } of entries) {
    const destination = path.join(outputDirectory, output);
    const bytes = await readFile(source);
    hash.update(output).update('\0').update(bytes).update('\0');
    await mkdir(path.dirname(destination), { recursive: true });
    await copyFile(source, destination);
  }

  hash.update(workerTemplate);
  const cacheName = `petits-moments-${hash.digest('hex').slice(0, 16)}`;
  const appShell = ['./', ...entries.map(({ output }) => `./${output}`)];
  const worker = [
    '// Generated by npm run build. Edit src/service-worker.js instead.',
    `const CACHE = ${JSON.stringify(cacheName)};`,
    `const APP_SHELL = ${JSON.stringify(appShell, null, 2)};`,
    workerTemplate,
  ].join('\n');

  await writeFile(path.join(outputDirectory, 'sw.js'), worker);
  if (!quiet) console.log(`Built ${entries.length + 1} files in dist/ (${cacheName}).`);
  return { files: entries.length + 1, cacheName };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildSite();
}
